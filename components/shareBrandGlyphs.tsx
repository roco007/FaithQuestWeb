/**
 * Glyphs for the share sheet's app row.
 *
 * Split out from `ShareLink` so the behaviour there stays about *how* a share is
 * delivered, while this file is only about *what it looks like* — and so the
 * provenance of every mark is stated in one place.
 *
 * **Brand marks** (WhatsApp, Facebook, X) are the official outlines from
 * [Simple Icons](https://simpleicons.org), which is CC0-1.0: public domain, no
 * attribution required, though the source is recorded here anyway. They are used
 * the way the brand guidelines intend — as the disc for that service's own
 * share button, on that service's own colour.
 *
 * **Generic glyphs** (Messages, Email) are deliberately *not* brand marks.
 * There is no canonical mark for "text message" or "email" that any one company
 * does not also own: Apple's Messages, Google's Messages, Messenger and SMS are
 * four different logos for the same tap, and a web page cannot know which is
 * installed. Drawing a plain bubble and envelope is the honest option — shipping
 * Google's Messages mark for a generic SMS target would misrepresent what the
 * tap does, the same mistake as using a Twitter bird for X.
 */

interface GlyphProps {
  size?: number;
  className?: string;
}

